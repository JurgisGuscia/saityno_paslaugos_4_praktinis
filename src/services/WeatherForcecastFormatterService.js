export default class WeatherForecastFormatterService {
  format(weatherForecast, eventDate) {
    if (!weatherForecast) {
      return {
        error: 'Weather data failed to load',
      };
    }
    if (!eventDate) {
      return {
        error: 'Event date is missing',
      };
    }
    const eventDateString = eventDate.toISOString();
    // construct time, temperature, humidity, rain, cloud cover, wind speed and direction arrays for the event date
    const times = [];
    const temperatures = [];
    const humidities = [];
    const apparentTemperatures = [];
    const rain = [];
    const clouds = [];
    const windSpeeds = [];
    const windDirections = [];
    //if event is later than 16 days, asign last date for weather forecast
    for (
      let i = weatherForecast.hourly.time.length - 24;
      i < weatherForecast.hourly.time.length;
      i++
    ) {
      times.push(weatherForecast.hourly.time[i]);
      temperatures.push(weatherForecast.hourly.temperature_2m[i]);
      humidities.push(weatherForecast.hourly.relative_humidity_2m[i]);
      apparentTemperatures.push(weatherForecast.hourly.apparent_temperature[i]);
      rain.push(weatherForecast.hourly.rain[i]);
      clouds.push(weatherForecast.hourly.cloud_cover[i]);
      windSpeeds.push(weatherForecast.hourly.wind_speed_10m[i]);
      windDirections.push(weatherForecast.hourly.wind_direction_10m[i]);
    }
    //returned date matches event date, reasign value with correct ones
    for (let i = 0; i < weatherForecast.hourly.time.length; i++) {
      if (weatherForecast.hourly.time[i].slice(0, 10) === eventDateString.slice(0, 10)) {
        times.push(weatherForecast.hourly.time[i]);
        temperatures.push(weatherForecast.hourly.temperature_2m[i]);
        humidities.push(weatherForecast.hourly.relative_humidity_2m[i]);
        apparentTemperatures.push(weatherForecast.hourly.apparent_temperature[i]);
        rain.push(weatherForecast.hourly.rain[i]);
        clouds.push(weatherForecast.hourly.cloud_cover[i]);
        windSpeeds.push(weatherForecast.hourly.wind_speed_10m[i]);
        windDirections.push(weatherForecast.hourly.wind_direction_10m[i]);
      }
    }
    //create a string for each hour data output
    const formatedWeatherForecastData = [];
    for (let i = 0; i < times.length; i++) {
      formatedWeatherForecastData.push(
        'Time:' +
          times[i] +
          ', Temperature: ' +
          temperatures[i] +
          '°C, Humidity: ' +
          humidities[i] +
          '%, Apparent Temperature: ' +
          apparentTemperatures[i] +
          '°C, Rain: ' +
          rain[i] +
          'mm, Cloud Cover: ' +
          clouds[i] +
          '%, Wind Speed: ' +
          windSpeeds[i] +
          'km/h, Wind Direction: ' +
          windDirections[i] +
          '°',
      );
    }
    //create output object
    const formatedWeatherForecast = {
      latitude: weatherForecast.latitude,
      longitude: weatherForecast.longitude,
      Temperature_units: weatherForecast.hourly_units.temperature_2m,
      Relative_humidity_units: weatherForecast.hourly_units.relative_humidity_2m,
      Apparent_temperature_units: weatherForecast.hourly_units.apparent_temperature,
      Rain_units: weatherForecast.hourly_units.rain,
      Cloud_cover_units: weatherForecast.hourly_units.cloud_cover,
      Wind_speed_units: weatherForecast.hourly_units.wind_speed_10m,
      Wind_direction_units: weatherForecast.hourly_units.wind_direction_10m,
      Weather_forecast: formatedWeatherForecastData,
    };

    return formatedWeatherForecast;
  }
}

